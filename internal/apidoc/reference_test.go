package apidoc

import (
	"bytes"
	"flag"
	"os"
	"path/filepath"
	"slices"
	"testing"
)

// update writes the reference rather than comparing it: task docs:api.
var update = flag.Bool("update", false, "write "+OutputDir+" from the packages' doc comments")

// repoRoot is the repository's root from this package's directory.
const repoRoot = "../.."

// docMode is the mode a written reference file gets.
const docMode = 0o644

// The reference in docs/api is what the packages' doc comments generate,
// file for file, with no file left over: a doc comment changed without
// task docs:api fails here.
func TestReferenceIsCurrent(t *testing.T) {
	want, err := Render(repoRoot)
	if err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join(repoRoot, filepath.FromSlash(OutputDir))
	if *update {
		writeReference(t, dir, want)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("%v: run task docs:api", err)
	}
	var have []string
	for _, e := range entries {
		have = append(have, e.Name())
	}
	for name, body := range want {
		got, err := os.ReadFile(filepath.Join(dir, name))
		switch {
		case err != nil:
			t.Errorf("%s/%s: %v: run task docs:api", OutputDir, name, err)
		case !bytes.Equal(got, body):
			t.Errorf("%s/%s differs from the doc comments: run task docs:api", OutputDir, name)
		}
	}
	for _, name := range have {
		if _, ok := want[name]; !ok {
			t.Errorf("%s/%s is generated by nothing: run task docs:api", OutputDir, name)
		}
	}
	if !slices.Contains(have, IndexFile) {
		t.Errorf("%s has no %s", OutputDir, IndexFile)
	}
}

// writeReference replaces dir's files with files.
func writeReference(t *testing.T, dir string, files map[string][]byte) {
	t.Helper()
	if err := os.RemoveAll(dir); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), body, docMode); err != nil {
			t.Fatal(err)
		}
	}
}
