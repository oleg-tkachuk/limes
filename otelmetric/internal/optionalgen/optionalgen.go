// Package optionalgen writes otelmetric's withOptional: the decorator
// implements each optional interface of package meter the store it wraps
// does, and none it does not, so it needs one struct type per mix of them —
// two to the power of their number. Written by hand, a fifth interface
// would be sixteen more cases to get right; written from Optional, it is one
// more line.
package optionalgen

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// Interface is an optional interface the decorator forwards: its name in
// package meter, and the otelmetric type that forwards it, holding the
// inner store as that interface in its one field.
type Interface struct {
	Name      string
	Forwarder string
}

// Optional is every optional interface the decorator forwards, in the order
// each mix embeds them.
var Optional = []Interface{
	{Name: "CopyUsageReader", Forwarder: "copyUsageReader"},
	{Name: "TenantUsageEraser", Forwarder: "tenantUsageEraser"},
	{Name: "MatchingReleaser", Forwarder: "matchingReleaser"},
	{Name: "TenantReservationLister", Forwarder: "tenantReservationLister"},
	{Name: "Leaser", Forwarder: "leaser"},
}

// File is the generated file's name in otelmetric.
const File = "optional_gen.go"

// header opens the file, marking it generated for go vet and reviewers.
const header = `// Code generated by internal/optionalgen; DO NOT EDIT.

package otelmetric

import "github.com/oleg-tkachuk/limes/meter"

// withOptional is m, which wraps inner, implementing each optional
// interface inner does, and none it does not: one case per mix, every one
// first and the fewest last.
func withOptional(m *meteringStore, inner meter.UsageStore) meter.UsageStore {
`

// Source is the generated file, formatted.
func Source() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	for i, o := range Optional {
		fmt.Fprintf(&b, "\tinner%d, is%d := inner.(meter.%s)\n", i, i, o.Name)
	}
	for i, o := range Optional {
		fmt.Fprintf(&b, "\tf%d := %s{inner%d}\n", i, o.Forwarder, i)
	}
	b.WriteString("\tswitch {\n")
	for _, mix := range mixes(len(Optional)) {
		var cond, fields, values []string
		for _, i := range mix {
			cond = append(cond, fmt.Sprintf("is%d", i))
			fields = append(fields, Optional[i].Forwarder)
			values = append(values, fmt.Sprintf("f%d", i))
		}
		fmt.Fprintf(&b, "\tcase %s:\n\t\treturn &struct {\n\t\t\t*meteringStore\n\t\t\t%s\n\t\t}{m, %s}\n",
			strings.Join(cond, " && "), strings.Join(fields, "\n\t\t\t"), strings.Join(values, ", "))
	}
	b.WriteString("\t}\n\treturn m\n}\n")
	return format.Source(b.Bytes())
}

// mixes is every non-empty subset of n interfaces, as their indexes
// ascending, the largest first — a switch takes the first case that holds —
// and those of one size in the order of their bits.
func mixes(n int) [][]int {
	var out [][]int
	for size := n; size > 0; size-- {
		for set := (1 << n) - 1; set > 0; set-- {
			var mix []int
			for i := range n {
				if set&(1<<(n-1-i)) != 0 {
					mix = append(mix, i)
				}
			}
			if len(mix) == size {
				out = append(out, mix)
			}
		}
	}
	return out
}
